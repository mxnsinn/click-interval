const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bridge', {
  configure: config => ipcRenderer.send('configure', config),
  restartBackend: () => ipcRenderer.send('restart-backend'),
  openCustomDropdown: payload => ipcRenderer.send('open-custom-dropdown', payload),
  closeCustomDropdown: () => ipcRenderer.send('close-custom-dropdown'),
  selectCustomDropdownOption: value => ipcRenderer.send('custom-dropdown-select', { value }),
  showHoverHint: payload => ipcRenderer.send('show-hover-hint', payload),
  hideHoverHint: () => ipcRenderer.send('hide-hover-hint'),
  reportHoverHintPainted: token => ipcRenderer.send('hover-hint-painted', { token }),
  getWindowContext: () => ipcRenderer.sendSync('get-window-context'),
  setActiveTool: tool => ipcRenderer.send('set-active-tool', tool),
  selectToolMenuAction: payload => ipcRenderer.send('tool-menu-action', payload),
  loadHotkey: () => ipcRenderer.sendSync('load-hotkey'),
  saveHotkey: hotkey => ipcRenderer.send('save-hotkey', hotkey),
  loadPreferences: () => ipcRenderer.sendSync('load-preferences'),
  savePreferences: preferences => ipcRenderer.send('save-preferences', preferences),
  loadMacroState: () => ipcRenderer.sendSync('load-macro-state'),
  saveMacroState: value => ipcRenderer.send('save-macro-state', value),
  loadMacroLibrary: () => ipcRenderer.sendSync('load-macro-library'),
  saveMacroLibrary: value => ipcRenderer.send('save-macro-library', value),
  uiReady: () => ipcRenderer.send('ui-ready'),
  openHotkeyWindow: mode => ipcRenderer.send('open-hotkey-window', mode),
  loadHotkeyDialog: () => ipcRenderer.sendSync('load-hotkey-dialog'),
  selectHotkey: hotkey => ipcRenderer.send('hotkey-selected', hotkey),
  selectEmergencyHotkey: hotkey => ipcRenderer.send('emergency-hotkey-selected', hotkey),
  selectMacroTrigger: hotkey => ipcRenderer.send('macro-trigger-selected', hotkey),
  selectMacroRecordHotkey: hotkey => ipcRenderer.send('macro-record-hotkey-selected', hotkey),
  selectMacroPlayHotkey: hotkey => ipcRenderer.send('macro-play-hotkey-selected', hotkey),
  openMessageWindow: payload => ipcRenderer.send('open-message-window', payload),
  openMacroNameWindow: payload => ipcRenderer.send('open-macro-name-window', payload),
  loadMacroNameDialog: () => ipcRenderer.sendSync('load-macro-name-dialog'),
  submitMacroName: name => ipcRenderer.send('submit-macro-name', name),
  openMacroDeleteWindow: payload => ipcRenderer.send('open-macro-delete-window', payload),
  loadMacroDeleteDialog: () => ipcRenderer.sendSync('load-macro-delete-dialog'),
  confirmMacroDelete: () => ipcRenderer.send('confirm-macro-delete'),
  closeCurrentWindow: () => ipcRenderer.send('close-current-window'),
  windowControl: action => ipcRenderer.send('window-control', action),
  checkForUpdates: () => ipcRenderer.send('check-for-updates'),
  installUpdate: () => ipcRenderer.send('install-update'),
  saveMacroFile: payload => ipcRenderer.invoke('save-macro-file', payload),
  openMacroFile: () => ipcRenderer.invoke('open-macro-file'),
  pickSmartArea: () => ipcRenderer.invoke('pick-smart-area'),
  confirmUnsavedMacro: () => ipcRenderer.invoke('confirm-unsaved-macro'),
  resolveUnsavedMacro: shouldSave => ipcRenderer.send('resolve-unsaved-macro', shouldSave),
  onBackendEvent: callback => ipcRenderer.on('backend-event', (_event, payload) => callback(payload)),
  onHotkeySelected: callback => ipcRenderer.on('hotkey-selected', (_event, payload) => callback(payload)),
  onHotkeyWindowCancelled: callback => ipcRenderer.on('hotkey-window-cancelled', (_event, payload) => callback(payload || {})),
  onEmergencyHotkeySelected: callback => ipcRenderer.on('emergency-hotkey-selected', (_event, payload) => callback(payload)),
  onMacroTriggerSelected: callback => ipcRenderer.on('macro-trigger-selected', (_event, payload) => callback(payload)),
  onMacroRecordHotkeySelected: callback => ipcRenderer.on('macro-record-hotkey-selected', (_event, payload) => callback(payload)),
  onMacroPlayHotkeySelected: callback => ipcRenderer.on('macro-play-hotkey-selected', (_event, payload) => callback(payload)),
  onUpdateStatus: callback => ipcRenderer.on('update-status', (_event, payload) => callback(payload)),
  onMessageData: callback => ipcRenderer.on('message-data', (_event, payload) => callback(payload)),
  onMacroNameCreated: callback => ipcRenderer.on('macro-name-created', (_event, payload) => callback(payload)),
  onMacroDeleteConfirmed: callback => ipcRenderer.on('macro-delete-confirmed', (_event, payload) => callback(payload)),
  onToolLayoutState: callback => ipcRenderer.on('tool-layout-state', (_event, payload) => callback(payload)),
  onPopupModalState: callback => ipcRenderer.on('popup-modal-state', (_event, payload) => callback(payload)),
  onCustomDropdownData: callback => ipcRenderer.on('custom-dropdown-data', (_event, payload) => callback(payload)),
  onCustomDropdownSelected: callback => ipcRenderer.on('custom-dropdown-selected', (_event, payload) => callback(payload)),
  onCustomDropdownClosed: callback => ipcRenderer.on('custom-dropdown-closed', (_event, payload) => callback(payload)),
  onHoverHintHidden: callback => ipcRenderer.on('hover-hint-hidden', () => callback()),
  onHoverHintContent: callback => ipcRenderer.on('hover-hint-content', (_event, payload) => callback(payload))
});
